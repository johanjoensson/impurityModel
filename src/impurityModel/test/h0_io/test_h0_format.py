"""Tests for the ``.h0`` interchange format (``doc/h0_file_format.md``).

The fixtures are **hand-authored from the spec**, not generated by either implementation.
That is deliberate: rspt2spectra and impurityModel implement the format independently, so a
fixture produced by one of them would only prove that implementation self-consistent, and
whichever repo generated it would have to land first before the other could test anything.
"""

import json
from pathlib import Path

import numpy as np
import pytest

from impurityModel.ed import h0_format
from impurityModel.ed.h0_format import H0FormatError

FIXTURES = Path(__file__).parent
INDEX_FIXTURE = FIXTURES / "golden_h0_v1_index.h0"
RYDBERG_FIXTURE = FIXTURES / "golden_h0_v1_rydberg.h0"


def _header_of(path):
    text = path.read_text()
    return json.loads(text.splitlines()[1])


def _rewrite(tmp_path, name, *, header_update=None, terms=None, source=INDEX_FIXTURE):
    """Copy a fixture with its header patched and/or its terms replaced."""
    lines = source.read_text().splitlines()
    header = json.loads(lines[1])
    header.update(header_update or {})
    body = terms if terms is not None else lines[3:]
    out = tmp_path / name
    out.write_text("\n".join([lines[0], json.dumps(header), "--", *body]) + "\n")
    return out


# --------------------------------------------------------------------------------------
# The index fixture: values encode their own indices, so any permutation, transpose or
# conjugation error changes the asserted result.
# --------------------------------------------------------------------------------------


def test_index_fixture_exact_operator_dict():
    parsed = h0_format.read_h0_file(INDEX_FIXTURE)

    assert parsed.n_orb == 8
    assert parsed.impurity_orbitals == {0: (0, 1, 2, 3)}
    assert parsed.impurity_indices == [0, 1, 2, 3]
    assert parsed.n_imp == 4
    assert parsed.valence_bath == (4, 5)
    assert parsed.conduction_bath == (6, 7)
    assert parsed.unit == "eV"
    assert parsed.energy_reference == "fermi"
    assert parsed.basis == "spherical"
    assert parsed.contains_soc is False

    # The fixture is the Hermitian part of H[i, j] = (10i + j) + 0.5j*(i - j), i.e.
    # 5.5*(i + j) + 0.5j*(i - j). The real part fixes the index *sum* and the imaginary part
    # the signed difference, so no permutation, transpose or conjugation can go unnoticed.
    h = parsed.to_matrix()
    expected = np.array([[5.5 * (i + j) + 0.5j * (i - j) for j in range(8)] for i in range(8)])
    np.testing.assert_array_equal(h, expected)


def test_index_fixture_is_hermitian_and_diagonal_is_real():
    h = h0_format.read_h0_file(INDEX_FIXTURE).to_matrix()
    np.testing.assert_array_equal(h, h.conj().T)
    np.testing.assert_array_equal(h.diagonal().imag, np.zeros(8))


def test_rydberg_fixture_is_converted_to_ev():
    parsed = h0_format.read_h0_file(RYDBERG_FIXTURE)

    assert parsed.unit == "eV"
    assert parsed.header["unit"] == "Ry"
    # The conversion is asserted on the value, not merely on the key being present.
    assert parsed.h0[((0, "c"), (0, "a"))] == pytest.approx(1.0 * h0_format.RY_TO_EV)
    assert parsed.h0[((0, "c"), (2, "a"))] == pytest.approx(0.25 * h0_format.RY_TO_EV)


