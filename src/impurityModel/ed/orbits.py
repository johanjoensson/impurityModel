"""Symmetry orbits of determinants, for orbit-closed selection and truncation of the ground-state basis.

The ground state and every thermal state must have all the symmetries of ``H``, even at the cost of
energy. Under a binding cap, picking determinants one by one splits a degenerate multiplet: members of one
orbit tie in score, and the tie is broken by key order. Here a selection or a cut acts on whole **orbits**.

An orbit is generated by

* the detected signed permutations of ``H`` (spin flip, impurity-orbital transpositions with their bath
  chains; :func:`impurityModel.ed.label_symmetries.symmetry_generators`), as the closure of the group they
  generate (enumerated, capped at :data:`GROUP_CAP` elements), and
* when total spin is a symmetry (``su2``), **every spin arrangement** of a pair-occupation pattern at
  ``|2 S_z| <= M``, ``M`` the largest ``2 S_z`` of the seed. Not the ``S_+-`` ladder rows: a ladder row is not
  invariant under ``S^2`` at fixed ``S_z``, the full arrangement set is.

A determinant's *pattern* is the occupation (0, 1 or 2) of every spin pair; with ``su2`` off the pattern is
the occupation of every orbital. The canonical representative of an orbit is the image of the pattern with
the smallest hash under the group. Orbits are ranked by the **sum** of their members' scores, which
:meth:`~impurityModel.ed.manybody_basis.Basis.redistribute_block` accumulates at the owner of the
representative, so a rank sees the whole orbit's score without a gather.

Every ``Orbits`` method taking a ``basis`` is collective on its communicator and must be called by every
rank, an empty one included.
"""

from itertools import combinations
from math import comb

import numpy as np
from mpi4py import MPI

from impurityModel.ed import label_symmetries
from impurityModel.ed.ManyBodyUtils import ManyBodyState, SlaterDeterminant
from impurityModel.ed.mpi_root import on_root
from impurityModel.ed.spin_pairs import _spin_symmetric, bath_spin_pairs, impurity_spin_pairs
from impurityModel.ed.spin_pairs import spin_layout as resolve_spin_layout
from impurityModel.ed.symmetries import PARITY_TERM_TOL, conserves_sz, weighted_parts

#: Most elements of the symmetry group that are enumerated. A larger group is not closed over (the
#: orbit machinery then runs without it and says so in :attr:`Orbits.notes`).
GROUP_CAP = 4096

#: Most determinants one orbit may generate; a larger one is cut to its first arrangements (and noted).
ORBIT_CAP = 1 << 20

_HASH_WEIGHTS = np.random.RandomState(20261031).randint(1, 2**62, size=1 << 14, dtype=np.int64).astype(np.uint64) | 1


def _bits(dets, n_orb):
    """``(n, n_orb)`` 0/1 occupations of ``dets`` (MSB-first bytes)."""
    if not len(dets):
        return np.zeros((0, n_orb), dtype=np.uint8)
    raw = np.frombuffer(b"".join(bytes(d.to_bytearray()) for d in dets), dtype=np.uint8).reshape(len(dets), -1)
    return np.unpackbits(raw, axis=1)[:, :n_orb]


def _keys_of(bits, n_bytes):
    """``SlaterDeterminant`` per row of the 0/1 matrix ``bits``."""
    if not len(bits):
        return []
    packed = np.packbits(bits, axis=1)
    packed = np.pad(packed, ((0, 0), (0, n_bytes - packed.shape[1])))
    return [SlaterDeterminant.from_bytes(bytes(row)) for row in packed]


def _group_closure(generators, n_cols):
    """All products of the column permutations ``generators``, identity first, ``(G, n_cols)``; ``None`` if too big."""
    identity = tuple(range(n_cols))
    seen = {identity}
    frontier = [identity]
    while frontier:
        new = []
        for element in frontier:
            for g in generators:
                image = tuple(element[g[c]] for c in range(n_cols))
                if image not in seen:
                    if len(seen) >= GROUP_CAP:
                        return None
                    seen.add(image)
                    new.append(image)
        frontier = new
    return np.array(sorted(seen, key=lambda e: (e != identity, e)), dtype=np.int64)


def _arrangements(k, two_sz_max):
    """Spin arrangements of ``k`` open pairs with ``|2 S_z| <= two_sz_max``: ``(count, (count, k) up-flags)``."""
    ups = [u for u in range(k + 1) if abs(2 * u - k) <= two_sz_max]
    return sum(comb(k, u) for u in ups)


class Orbits:
    """The orbit structure of one sector solve: canonical forms, orbit sizes and members, and the two
    collective primitives :meth:`select_new` (admission) and :meth:`retain` (truncation).

    Parameters
    ----------
    n_orb, n_bytes : int
        Spin-orbital count and the basis's determinant width in bytes.
    group : ndarray ``(G, C)``
        Column permutations (identity first) acting on the pattern's ``C`` columns.
    pairs : ndarray ``(P, 2)`` or None
        ``(dn, up)`` of every spin pair when the pattern is pair occupations (``su2``), else ``None``
        (the pattern is the orbital occupation).
    two_sz_max : int
        ``M``: the arrangements are those with ``|2 S_z| <= M``.
    restrictions, weighted_restrictions
        The basis's: a generated member that violates them is not a member (``add_states`` does not filter).
    notes : list of str
        What was left out and why (a group over the cap, a generator that moved unpaired orbitals, ...).
    """

    def __init__(
        self, n_orb, n_bytes, group, pairs, two_sz_max, restrictions=None, weighted_restrictions=None, notes=()
    ):
        self.n_orb, self.n_bytes = int(n_orb), int(n_bytes)
        self.group = np.ascontiguousarray(group, dtype=np.int64)
        self.pairs = None if pairs is None else np.asarray(pairs, dtype=np.int64).reshape(-1, 2)
        self.two_sz_max = int(two_sz_max)
        self.restrictions = dict(restrictions or {})
        self.weighted_restrictions = list(weighted_restrictions or [])
        self.notes = list(notes)
        #: Optional ``bits -> bool mask``: a generated member that fails it is not a member. Restricts the orbits to
        #: one hard label's block (`sector_solver._solve_window_per_label`), where the group maps it onto others.
        self.det_filter = None
        self.n_cols = self.group.shape[1]
        self._weights = _HASH_WEIGHTS[: self.n_cols] if self.n_cols <= len(_HASH_WEIGHTS) else None
        if self._weights is None:
            raise ValueError("too many pattern columns for the orbit hash")
        self._arr = {}

    # -- patterns ---------------------------------------------------------------------------------------
    @property
    def trivial(self):
        """No symmetry to close over: the group is the identity and there are no spin arrangements."""
        return len(self.group) <= 1 and self.pairs is None

    def pattern(self, bits):
        """``(n, C)`` uint8 pattern of the occupation matrix ``bits``."""
        if self.pairs is None:
            return bits
        return (bits[:, self.pairs[:, 0]] + bits[:, self.pairs[:, 1]]).astype(np.uint8)

    def canonical(self, patterns):
        """``(rep, n_images)``: the canonical image of every pattern and how many distinct images it has."""
        n = len(patterns)
        if n == 0:
            return patterns.copy(), np.zeros(0, dtype=np.int64)
        rep = np.empty_like(patterns)
        n_images = np.empty(n, dtype=np.int64)
        chunk = max(1, int(2e7 // max(1, self.group.shape[0] * self.n_cols)))
        for lo in range(0, n, chunk):
            block = patterns[lo : lo + chunk]
            images = block[:, self.group]  # (m, G, C)
            with np.errstate(over="ignore"):
                codes = (images.astype(np.uint64) * self._weights).sum(axis=2, dtype=np.uint64)
            best = np.argmin(codes, axis=1)
            rep[lo : lo + chunk] = images[np.arange(len(block)), best]
            ordered = np.sort(codes, axis=1)
            n_images[lo : lo + chunk] = 1 + np.count_nonzero(ordered[:, 1:] != ordered[:, :-1], axis=1)
        return rep, n_images

    def size(self, rep, n_images):
        """Determinants in each orbit, before the restrictions: images times spin arrangements."""
        if self.pairs is None:
            return n_images.astype(np.int64)
        singles = np.count_nonzero(rep == 1, axis=1)
        arr = np.array([self._count(int(k)) for k in singles], dtype=np.int64)
        return n_images * arr

    def _count(self, k):
        if k not in self._arr:
            self._arr[k] = _arrangements(k, self.two_sz_max)
        return self._arr[k]

    def representative_det(self, rep):
        """The determinant standing for the orbit of pattern ``rep`` (a pair's single occupation is its up orbital)."""
        if self.pairs is None:
            return _keys_of(rep.astype(np.uint8), self.n_bytes)
        bits = np.zeros((len(rep), self.n_orb), dtype=np.uint8)
        bits[:, self.pairs[:, 1]] = rep >= 1
        bits[:, self.pairs[:, 0]] = rep == 2
        return _keys_of(bits, self.n_bytes)

    # -- members ----------------------------------------------------------------------------------------
    def _satisfies(self, bits):
        keep = np.ones(len(bits), dtype=bool)
        for orbitals, (low, high) in self.restrictions.items():
            n = bits[:, sorted(orbitals)].sum(axis=1)
            keep &= (n >= low) & (n <= high)
        for entry in self.weighted_restrictions:
            weights, (low, high), _tail = weighted_parts(entry)
            idx = sorted(weights)
            q = bits[:, idx].astype(np.int64) @ np.array([weights[i] for i in idx], dtype=np.int64)
            keep &= (q >= low) & (q <= high)
        if self.det_filter is not None:
            keep &= self.det_filter(bits)
        return keep

    def _spin_choices(self, k, two_sz_max):
        """``(m, k)`` 0/1 up-flags of the arrangements of ``k`` open pairs with ``|2 S_z| <= two_sz_max``."""
        rows = []
        for u in range(k + 1):
            if abs(2 * u - k) > two_sz_max:
                continue
            for up in combinations(range(k), u):
                flags = np.zeros(k, dtype=np.uint8)
                flags[list(up)] = 1
                rows.append(flags)
        return np.array(rows, dtype=np.uint8).reshape(len(rows), k)

    def members(self, rep_rows, two_sz_max=None, cap_orbits=True):
        """The members of the orbits with patterns ``rep_rows``, filtered by the restrictions: ``(m, n_orb)`` bits.

        ``two_sz_max=None`` uses ``M``; a larger value (truncation passes the pair count) takes every arrangement.
        """
        limit = self.two_sz_max if two_sz_max is None else two_sz_max
        out = []
        for rep in rep_rows:
            images = np.unique(rep[self.group], axis=0)  # distinct image patterns
            for image in images:
                if self.pairs is None:
                    out.append(image[None, :].astype(np.uint8))
                    continue
                singles = np.flatnonzero(image == 1)
                doubles = np.flatnonzero(image == 2)
                choices = self._spin_choices(len(singles), limit)
                if cap_orbits and len(choices) > ORBIT_CAP:
                    choices = choices[:ORBIT_CAP]
                    if "an orbit of open pairs was cut at ORBIT_CAP" not in self.notes:
                        self.notes.append("an orbit of open pairs was cut at ORBIT_CAP")
                bits = np.zeros((len(choices), self.n_orb), dtype=np.uint8)
                bits[:, self.pairs[doubles, 0]] = 1
                bits[:, self.pairs[doubles, 1]] = 1
                bits[:, self.pairs[singles, 1]] = choices
                bits[:, self.pairs[singles, 0]] = 1 - choices
                out.append(bits)
        if not out:
            return np.zeros((0, self.n_orb), dtype=np.uint8)
        bits = np.vstack(out)
        return bits[self._satisfies(bits)]

    # -- collective primitives --------------------------------------------------------------------------
    def _owned_orbits(self, basis, dets, columns):
        """Route ``columns`` (float arrays aligned with ``dets``) to the owners of the dets' orbit representatives.

        Returns ``(reps, sums)``: the patterns of the orbits this rank owns and the summed columns, summed over
        every rank's contribution. Collective; an empty rank contributes an explicit empty block.
        """
        comm = basis.comm if basis.is_distributed else None
        patterns = self.pattern(_bits(dets, self.n_orb))
        rep, _n = self.canonical(patterns)
        if len(rep):
            uniq, inverse = np.unique(rep, axis=0, return_inverse=True)
            inverse = inverse.reshape(-1)
            summed = [np.bincount(inverse, weights=np.asarray(c, dtype=float), minlength=len(uniq)) for c in columns]
        else:
            uniq, summed = rep, [np.zeros(0) for _ in columns]
        keys = self.representative_det(uniq)
        states = [ManyBodyState(dict(zip(keys, map(complex, s))), width=1) for s in summed]
        block = ManyBodyState.from_states(states)
        routed = basis.redistribute_block(block)
        routed_keys = routed.keys()
        amps = np.array(routed) if len(routed_keys) else np.zeros((0, len(columns)), dtype=complex)
        patterns = self.pattern(_bits(routed_keys, self.n_orb))
        del comm
        return patterns, np.real(amps)

    def select_new(self, basis, dets, scores, preselect, max_new):
        """Admit whole orbits: ``(new_keys, stats)``. Collective.

        ``dets``/``scores``/``preselect`` are this rank's candidates (determinants outside the basis that ``H``
        reaches, their importances, and the pre-selection mask). An orbit is a candidate when some member passes
        the pre-selection; it is ranked by the sum of all its members' scores. With ``max_new`` the orbits are
        taken best first while their sizes (upper bounds on what they add) fit ``max_new``; a tie group goes in
        whole or not at all, and the budget may be left under-filled. ``new_keys`` are the determinants this rank
        owns that the basis does not hold yet. ``stats`` has the keys of ``CIPSISolver._admit_top``.
        """
        comm = basis.comm if basis.is_distributed else None
        scores = np.asarray(scores, dtype=float)
        preselect = np.asarray(preselect, dtype=bool)
        passes = preselect.astype(float)
        reps, sums = self._owned_orbits(basis, dets, [scores, passes])
        total, candidate = sums[:, 0], sums[:, 1] > 0.5
        rep, n_images = self.canonical(reps)
        sizes = self.size(rep, n_images)
        selected = _select_by_budget(total, sizes, candidate, max_new, comm)
        chosen = rep[selected]
        bits = self.members(chosen)
        keys = _keys_of(bits, self.n_bytes)
        new_keys = basis.new_owned_keys(keys)
        n_candidates = _allreduce(comm, int(np.count_nonzero(preselect)))
        everything = _allreduce(comm, float(scores.sum()))
        admitted_mass = _allreduce(comm, float(total[selected].sum()))
        candidate_mass = _allreduce(comm, float(total[candidate].sum()))
        stats = {
            "n_candidates": n_candidates,
            "n_admitted": _allreduce(comm, len(new_keys)),
            "discarded_de2_mass": max(candidate_mass - admitted_mass, 0.0) if max_new is not None else 0.0,
            "subthreshold_de2_mass": _allreduce(comm, float(scores[~preselect].sum())),
            "residual_pt2": max(everything - admitted_mass, 0.0),
        }
        return new_keys, stats

    def retain(self, basis, dets, importance, target):
        """The subset of this rank's ``dets`` kept when the basis is cut to about ``target`` determinants. Collective.

        Orbits (the present members of each pattern class) are ranked by the sum of their members'
        ``importance`` and kept best first while their present sizes fit ``target``; a tie group goes in whole
        or not at all, so the cut may keep fewer than ``target`` by less than the largest orbit. Orbits with no
        importance at all fill the room left, in hash order.
        """
        comm = basis.comm if basis.is_distributed else None
        importance = np.asarray(importance, dtype=float)
        reps, sums = self._owned_orbits(basis, dets, [importance, np.ones(len(dets))])
        total, present = sums[:, 0], np.rint(sums[:, 1]).astype(np.int64)
        rep, _n = self.canonical(reps)
        selected = _select_by_budget(total, present, np.ones(len(total), dtype=bool), target, comm)
        # Fill to the target. An orbit whose members all carry zero importance is dropped by the ranking above,
        # which deletes support the cap had room for (measured: 163,974 -> 47,200 determinants on FeO). The room
        # left goes to those orbits in hash order -- a function of the orbit alone, so the filler is the same on
        # every rank count and never splits an orbit. It is second-order filler (zero amplitude on the manifold).
        room = int(target) - _allreduce(comm, int(present[selected].sum()))
        if room > 0:
            filler = ~selected & (total <= 0.0)
            hashed = np.array([d.get_hash() / 2.0**64 + 2.0**-64 for d in self.representative_det(rep)], dtype=float)
            selected = selected | _select_by_budget(hashed, present, filler, room, comm)
        # Every arrangement, not only |2 S_z| <= M: a present determinant must be found by its own pattern.
        bits = self.members(rep[selected], two_sz_max=self.n_cols if self.pairs is not None else 0, cap_orbits=False)
        routed = basis.redistribute_block(
            ManyBodyState(dict.fromkeys(_keys_of(bits, self.n_bytes), 1.0), width=1)
            if len(bits)
            else ManyBodyState({}, width=1)
        )
        members = set(routed.keys()) if basis.is_distributed else set(_keys_of(bits, self.n_bytes))
        return {d for d in dets if d in members}


def _allreduce(comm, value):
    return value if comm is None or comm.size == 1 else comm.allreduce(value, op=MPI.SUM)


def _select_by_budget(scores, sizes, candidate, budget, comm):
    """Local mask of the orbits taken best-score-first while their summed ``sizes`` stay within ``budget``.

    ``budget=None`` takes every candidate. The cutoff is a global bisection on the score, so a tie group is in or
    out together and every rank cuts at the same score.
    """
    candidate = np.asarray(candidate, dtype=bool) & (scores > 0.0)
    if budget is None:
        return candidate
    if budget <= 0:
        return np.zeros_like(candidate)
    # An orbit larger than the whole budget can never be taken; leaving it in would stop the best-first
    # prefix at it and take nothing (a truncation would then empty the basis).
    candidate = candidate & (sizes <= budget)
    total = _allreduce(comm, float(sizes[candidate].sum()))
    if total <= budget:
        return candidate
    lo_local = float(scores[candidate].min()) if candidate.any() else np.inf
    hi_local = float(scores[candidate].max()) if candidate.any() else -np.inf
    if comm is not None and comm.size > 1:
        low = comm.allreduce(lo_local, op=MPI.MIN)
        high = comm.allreduce(hi_local, op=MPI.MAX)
    else:
        low, high = lo_local, hi_local
    # F(t) = summed size of the orbits scoring at least t; decreasing. Find the smallest t with F(t) <= budget.
    lo, hi = np.log(low) - 1e-9, np.log(high) + 1e-9  # F(lo) > budget >= F(hi) = 0
    for _ in range(80):
        mid = 0.5 * (lo + hi)
        fill = _allreduce(comm, float(sizes[candidate & (scores >= np.exp(mid))].sum()))
        if fill > budget:
            lo = mid
        else:
            hi = mid
    taken = candidate & (scores >= np.exp(hi))
    if _allreduce(comm, int(np.count_nonzero(taken))) == 0 and _allreduce(comm, int(np.count_nonzero(candidate))) > 0:
        # Even the best tie group alone overshoots: take it anyway rather than nothing. A cut must keep
        # something, and the cap is a soft target for a whole orbit.
        best_local = float(scores[candidate].max()) if candidate.any() else -np.inf
        best = comm.allreduce(best_local, op=MPI.MAX) if comm is not None and comm.size > 1 else best_local
        taken = candidate & (scores >= best * (1.0 - 1e-12))
    return taken


def build_orbits(h_op, basis, *, spin_layout=None, comm=None):
    """The :class:`Orbits` of ``basis``'s sector solve, or ``None`` when there is no symmetry to close over. Collective.

    Decided on rank 0 and broadcast: the generators are detected on ``h_op`` (with the basis's restrictions),
    kept only if they map the spin pairs onto themselves, and the spin arrangements are closed over only when
    ``S^2`` is a symmetry and the restrictions are pair-closed. ``M`` is the largest ``|2 S_z|`` of the seed.
    """
    comm = basis.comm if basis.is_distributed else None

    def _detect():
        n_orb = max(basis.num_spin_orbitals, max((o for term in h_op.keys() for o, _ in term), default=-1) + 1)
        layout = spin_layout or resolve_spin_layout(h_op, basis.impurity_orbitals, basis.bath_states, None, n_orb)
        index_imp = impurity_spin_pairs(basis.impurity_orbitals)
        index_bath = bath_spin_pairs(basis.bath_states)
        sz_ok = layout.labelled and conserves_sz(h_op, layout.pairs, PARITY_TERM_TOL)
        su2 = bool(sz_ok and layout.su2 and _spin_symmetric(h_op, layout.pairs))
        pairs = list(layout.pairs) if sz_ok else index_imp + index_bath
        notes = []
        generators = []
        if label_symmetries.CERTIFY_LABEL_SYMMETRY:
            generators = label_symmetries.symmetry_generators(
                h_op,
                list(layout.imp_pairs) if sz_ok else index_imp,
                list(layout.bath_pairs) if sz_ok else index_bath,
                n_orb,
                restrictions=basis.restrictions,
                weighted_restrictions=basis.weighted_restrictions,
            )
        pair_array = np.array(pairs, dtype=np.int64).reshape(-1, 2)
        closed = su2 and len(pair_array) * 2 == n_orb and _pair_closed(pair_array, basis)
        if su2 and not closed:
            notes.append("spin arrangements not closed: an orbital is unpaired or a restriction splits a spin pair")
        columns = None
        group = None
        if closed:
            columns = len(pair_array)
            index_of = {}
            for p, (dn, up) in enumerate(pair_array):
                index_of[int(dn)] = p
                index_of[int(up)] = p
            perms = []
            for sp in generators:
                image = []
                ok = True
                for dn, up in pair_array:
                    a, b = index_of.get(sp.perm[int(dn)]), index_of.get(sp.perm[int(up)])
                    if a is None or a != b:
                        ok = False
                        break
                    image.append(a)
                if ok:
                    perms.append(tuple(image))
                else:
                    notes.append("a symmetry does not map spin pairs onto spin pairs: left out")
            group = _group_closure(perms, columns)
        else:
            columns = n_orb
            perms = [tuple(sp.perm) for sp in generators]
            group = _group_closure(perms, columns)
        if group is None:
            notes.append(f"the symmetry group has more than {GROUP_CAP} elements: not closed over")
            group = np.arange(columns, dtype=np.int64)[None, :]
        return (group, pair_array if closed else None, n_orb, notes)

    # A rank-0 failure is raised on every rank before the broadcast of the result.
    head = on_root(comm, _detect)
    if comm is not None:
        head = comm.bcast(head, root=0)
    group, pair_array, n_orb, notes = head
    two_sz_max = 0
    if pair_array is not None:
        # The largest |2 S_z| of the seed bounds the 2 S of every multiplet the solve holds.
        sz = _bits(list(basis.local_basis), n_orb).astype(np.int64)
        local = int(np.max(np.abs((sz[:, pair_array[:, 1]] - sz[:, pair_array[:, 0]]).sum(axis=1)))) if len(sz) else 0
        two_sz_max = local if comm is None else int(comm.allreduce(local, op=MPI.MAX))
    orbits = Orbits(
        n_orb,
        basis.n_bytes,
        group,
        pair_array,
        two_sz_max,
        restrictions=basis.restrictions,
        weighted_restrictions=basis.weighted_restrictions,
        notes=notes,
    )
    return None if orbits.trivial else orbits


def _pair_closed(pairs, basis):
    """Whether every restriction treats the two orbitals of each spin pair alike (S^2-invariant windows)."""
    partner = {}
    for dn, up in pairs:
        partner[int(dn)], partner[int(up)] = int(up), int(dn)
    for orbitals in basis.restrictions or {}:
        if any(o not in partner or partner[o] not in orbitals for o in orbitals):
            return False
    for entry in basis.weighted_restrictions or []:
        weights, _limits, _tail = weighted_parts(entry)
        if any(partner.get(o) is None or weights.get(partner[o]) != w for o, w in weights.items()):
            return False
    return True
