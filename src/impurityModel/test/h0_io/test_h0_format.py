@pytest.mark.parametrize(
    "bad_term, pattern",
    [
        ("0 0 1.0", "4 whitespace-separated fields"),
        ("0 0 1.0 0.0 0.0", "4 whitespace-separated fields"),
        ("a 0 1.0 0.0", "integer orbital indices"),
        ("0 0 x 0.0", "real amplitudes"),
        ("0 0 nan 0.0", "must be finite"),
        ("0 0 1.0 inf", "must be finite"),
    ],
)
def test_malformed_term_line_raises_with_line_number(tmp_path, bad_term, pattern):
    out = _rewrite(tmp_path, "term.h0", terms=[bad_term])
    with pytest.raises(H0FormatError, match=pattern) as excinfo:
        h0_format.read_h0_file(out)
    assert "term.h0:4:" in str(excinfo.value)


