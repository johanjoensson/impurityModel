@pytest.mark.parametrize("transform", ["crlf", "bom", "no_trailing_newline", "cr"])
def test_byte_level_variations_parse_identically(tmp_path, transform):
    reference = h0_format.read_h0_file(INDEX_FIXTURE).h0
    raw = INDEX_FIXTURE.read_bytes()
    if transform == "crlf":
        raw = raw.replace(b"\n", b"\r\n")
    elif transform == "cr":
        raw = raw.replace(b"\n", b"\r")
    elif transform == "bom":
        raw = b"\xef\xbb\xbf" + raw
    else:
        raw = raw.rstrip(b"\n")

    out = tmp_path / f"{transform}.h0"
    out.write_bytes(raw)
    assert h0_format.read_h0_file(out).h0 == reference


def test_double_dash_inside_a_json_string_does_not_truncate_the_header(tmp_path):
    """The `--` separator is cosmetic; the header's extent comes from JSON's grammar."""
    out = _rewrite(tmp_path, "dashes.h0", header_update={"producer": {"name": "a--b"}})
    parsed = h0_format.read_h0_file(out)
    assert parsed.header["producer"]["name"] == "a--b"
    assert parsed.n_orb == 8


def test_comments_and_blank_lines_between_terms_are_ignored(tmp_path):
    out = _rewrite(tmp_path, "comments.h0", terms=["0 0 1.0 0.0", "", "# a comment", "  ", "1 1 2.0 0.0"])
    parsed = h0_format.read_h0_file(out)
    assert parsed.h0 == {((0, "c"), (0, "a")): 1.0 + 0j, ((1, "c"), (1, "a")): 2.0 + 0j}


