def test_round_trip_is_exact(tmp_path):
    """Exact dict equality, not assert_allclose: repr floats make it achievable.

    A tolerance-based comparison would be blind to a dropped term, which is the failure
    mode that actually occurred with the predecessor's fixed-point format.
    """
    original = h0_format.read_h0_file(INDEX_FIXTURE)
    out = tmp_path / "round_trip.h0"
    h0_format.write_h0_file(out, original.to_matrix(), impurity_orbitals=original.impurity_orbitals)

    reread = h0_format.read_h0_file(out)
    assert reread.h0 == original.h0
    assert reread.n_orb == original.n_orb
    assert reread.impurity_orbitals == original.impurity_orbitals


def test_round_trip_survives_awkward_magnitudes(tmp_path):
    """Small elements round-trip bit-for-bit; %.15f wrote these with 4 digits, or as 0.

    drop_tolerance=0 isolates precision from the scale-relative drop rule -- the 1e-10 and
    1e-12 elements here are genuine f-shell magnitudes, and at the default 1e-12 relative
    threshold they would legitimately be discarded next to the 1234 element.
    """
    h = np.zeros((3, 3), dtype=complex)
    h[0, 0] = -4.126921785541874
    h[0, 1] = 1.2345678901234567e-10 + 6.599434672757963e-12j
    h[1, 0] = np.conj(h[0, 1])
    h[2, 2] = 1234.5678901234567

    out = tmp_path / "small.h0"
    h0_format.write_h0_file(out, h, impurity_orbitals={0: [0, 1]}, drop_tolerance=0.0)
    np.testing.assert_array_equal(h0_format.read_h0_file(out).to_matrix(), h)


def test_default_drop_tolerance_is_scale_relative(tmp_path):
    """The threshold is relative to max|H| and applied to the (i,j)/(j,i) pair together."""
    h = np.diag([1000.0, 1.0, 1.0]).astype(complex)
    h[1, 2] = 1e-10  # below the 1e-12 * 1000 = 1e-9 cutoff, though large next to |H[1,1]|
    h[2, 1] = 1e-10

    out = tmp_path / "rel.h0"
    h0_format.write_h0_file(out, h, impurity_orbitals={0: [0]})
    got = h0_format.read_h0_file(out).to_matrix()
    assert got[1, 2] == 0.0 and got[2, 1] == 0.0
    assert got[0, 0] == 1000.0


def test_writer_symmetrizes_and_drops_pairwise(tmp_path):
    """A non-Hermitian input is symmetrized, and negligible pairs leave with both halves."""
    h = np.array([[1.0, 3.0, 1e-18], [1.0, 2.0, 0.0], [0.0, 0.0, 4.0]], dtype=complex)
    out = tmp_path / "sym.h0"
    h0_format.write_h0_file(out, h, impurity_orbitals={0: [0, 1]})

    got = h0_format.read_h0_file(out).to_matrix()
    assert got[0, 1] == 2.0 and got[1, 0] == 2.0
    # Below drop_tolerance * max|H|; the (2,0) partner goes with it, so the key sets match.
    assert got[0, 2] == 0.0 and got[2, 0] == 0.0


def test_writer_rejects_non_finite(tmp_path):
    with pytest.raises(H0FormatError, match="non-finite"):
        h0_format.write_h0_file(tmp_path / "nan.h0", np.array([[np.nan]]), impurity_orbitals={0: [0]})


